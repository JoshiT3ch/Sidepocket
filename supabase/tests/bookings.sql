-- Isolated rollback fixtures: never reserve a real player's slot.
begin;
do $test$
declare
  owner_id uuid:=gen_random_uuid(); player_id uuid:=gen_random_uuid(); other_id uuid:=gen_random_uuid(); reviewer_id uuid:=gen_random_uuid();
  court_id uuid; v_application_id uuid; booking_id uuid; result jsonb; payload jsonb; blocked boolean; tomorrow text:=(((now() at time zone 'Asia/Manila')::date)+1)::text;
begin
  if has_function_privilege('anon','public.sideout_booking(text,jsonb)','execute') then raise exception 'TEST anonymous gateway'; end if;
  if has_table_privilege('authenticated','sideout.player_verifications','insert') or has_table_privilege('authenticated','sideout.court_reviewers','insert') then raise exception 'TEST self verification'; end if;
  if has_table_privilege('authenticated','sideout.court_applications','select') then raise exception 'TEST private application exposure'; end if;
  insert into auth.users(id,email) values(owner_id,'owner@bookings.invalid'),(player_id,'player@bookings.invalid'),(other_id,'other@bookings.invalid'),(reviewer_id,'reviewer@bookings.invalid');
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform sideout.ensure(owner_id);
  update sideout.profiles set data=data||'{"avatarCreated":true,"isVerified":true}' where user_id=owner_id;
  result:=public.sideout_profile();
  if (result->>'isVerified')::boolean then raise exception 'TEST editable JSON granted verification'; end if;
  payload:=jsonb_build_object('name','Fixture court','address','Fixture address, Valencia City','description','Indoor physical pickleball court','contact','owner@bookings.invalid','evidence','Operator can verify this fixture reference','rate',100,'openHour',6,'closeHour',22,'authority','on');
  blocked:=false;
  begin perform public.sideout_booking('apply',payload); exception when others then blocked:=sqlerrm like 'Only verified%'; end;
  if not blocked then raise exception 'TEST unverified application'; end if;
  insert into sideout.player_verifications(user_id,verified_until) values(owner_id,now()+interval '1 month');
  execute 'set local role authenticated';
  result:=public.sideout_booking('apply',payload);v_application_id:=(result->>'applicationId')::uuid;
  execute 'reset role';
  blocked:=false;
  begin perform public.sideout_booking('review',jsonb_build_object('applicationId',v_application_id,'approve',true)); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'TEST nonreviewer approval'; end if;
  insert into sideout.court_reviewers values(owner_id),(reviewer_id);
  blocked:=false;
  begin perform public.sideout_booking('review',jsonb_build_object('applicationId',v_application_id,'approve',true)); exception when others then blocked:=sqlerrm like 'Another reviewer%'; end;
  if not blocked then raise exception 'TEST self approval'; end if;
  perform set_config('request.jwt.claim.sub',reviewer_id::text,true);
  perform public.sideout_booking('review',jsonb_build_object('applicationId',v_application_id,'approve',false,'note','Please supply clearer evidence.'));
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  perform public.sideout_booking('apply',payload||jsonb_build_object('applicationId',v_application_id));
  perform set_config('request.jwt.claim.sub',reviewer_id::text,true);
  perform public.sideout_booking('review',jsonb_build_object('applicationId',v_application_id,'approve',true));
  select id into court_id from sideout.bookable_courts where sideout.bookable_courts.application_id=v_application_id;
  if court_id is null then raise exception 'TEST approved court not published'; end if;
  perform set_config('request.jwt.claim.sub',player_id::text,true);
  execute 'set local role authenticated';
  result:=public.sideout_booking('list',jsonb_build_object('courtId',court_id,'date',tomorrow));
  if jsonb_array_length(result->'reviews')<>0 or jsonb_array_length(result->'applications')<>0 or jsonb_array_length(result->'ownerBookings')<>0 then raise exception 'TEST private records leaked'; end if;
  result:=public.sideout_booking('reserve',jsonb_build_object('courtId',court_id,'date',tomorrow,'hour',8));booking_id:=(result->>'bookingId')::uuid;
  result:=public.sideout_booking('reserve',jsonb_build_object('courtId',court_id,'date',tomorrow,'hour',8));
  if (result->>'bookingId')::uuid<>booking_id then raise exception 'TEST retry not idempotent'; end if;
  execute 'reset role';
  perform set_config('request.jwt.claim.sub',other_id::text,true);
  blocked:=false;
  begin perform public.sideout_booking('reserve',jsonb_build_object('courtId',court_id,'date',tomorrow,'hour',8)); exception when others then blocked:=sqlerrm like 'Someone just booked%'; end;
  if not blocked then raise exception 'TEST double booking'; end if;
  blocked:=false;
  begin perform public.sideout_booking('cancel',jsonb_build_object('bookingId',booking_id)); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'TEST another player cancellation'; end if;
  blocked:=false;
  begin perform public.sideout_booking('reserve',jsonb_build_object('courtId',court_id,'date',tomorrow,'hour',23)); exception when others then blocked:=sqlerrm like 'Choose an available time%'; end;
  if not blocked then raise exception 'TEST closed hours accepted'; end if;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  result:=public.sideout_booking('list',jsonb_build_object('courtId',court_id,'date',tomorrow));
  if jsonb_array_length(result->'ownerBookings')<>1 then raise exception 'TEST owner reservations missing'; end if;
  perform public.sideout_booking('cancel',jsonb_build_object('bookingId',booking_id));
  perform set_config('request.jwt.claim.sub',other_id::text,true);
  perform public.sideout_booking('reserve',jsonb_build_object('courtId',court_id,'date',tomorrow,'hour',8));
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  update sideout.player_verifications set verified_until=now()-interval '1 second' where user_id=owner_id;
  blocked:=false;
  begin perform public.sideout_booking('apply',payload); exception when others then blocked:=sqlerrm like 'Only verified%'; end;
  if not blocked then raise exception 'TEST expired verification'; end if;
  perform set_config('request.jwt.claim.sub','',true);
  blocked:=false;
  begin perform public.sideout_booking('list','{}'); exception when insufficient_privilege then blocked:=true; end;
  if not blocked then raise exception 'TEST missing authentication'; end if;
end $test$;
rollback;
